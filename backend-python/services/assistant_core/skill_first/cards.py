"""Formal Agent Skill Cards for the HRM assistant.

These cards are the semantic contract for the Skill-first runtime. They are
intentionally separate from ``assistant_core.skill_cards``, which is still the
UI-facing launcher card list.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any, Dict, List, Optional

from .. import skill_registry


@dataclass(frozen=True)
class AgentSkillCard:
    id: str
    name: str
    domain: str
    description: str
    when_to_use: List[str]
    anti_examples: List[str]
    colloquial_examples: List[str]
    required_slots: List[str]
    optional_slots: List[str]
    slot_extraction_hints: Dict[str, str]
    risk_level: str
    side_effect: bool
    allowed_roles: List[str]
    executor: Dict[str, Any]
    confirmation_policy: str
    desensitization_policy: str
    verification_rules: List[str]
    fallback_policy: str
    priority: int = 0
    aliases: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


def _spec_value(tool: str, field: str, default: Any) -> Any:
    spec = skill_registry.get(tool)
    return getattr(spec, field, default) if spec else default


def _card(
    *,
    card_id: str,
    name: str,
    domain: str,
    tool: str,
    description: str,
    when_to_use: List[str],
    anti_examples: List[str],
    colloquial_examples: List[str],
    required_slots: Optional[List[str]] = None,
    optional_slots: Optional[List[str]] = None,
    slot_extraction_hints: Optional[Dict[str, str]] = None,
    executor: Optional[Dict[str, Any]] = None,
    confirmation_policy: Optional[str] = None,
    desensitization_policy: Optional[str] = None,
    verification_rules: Optional[List[str]] = None,
    fallback_policy: str = 'clarify_or_capture_failure_sample',
    priority: int = 0,
    aliases: Optional[List[str]] = None,
) -> AgentSkillCard:
    spec = skill_registry.get(tool)
    base_executor = {
        'tool': tool,
        'purpose': 'side_effect' if _spec_value(tool, 'side_effect', False) else 'query',
        'defaults': {},
    }
    if executor:
        base_executor.update(executor)
    side_effect = bool(base_executor.get('purpose') == 'side_effect' or _spec_value(tool, 'side_effect', False))
    return AgentSkillCard(
        id=card_id,
        name=name,
        domain=domain,
        description=description,
        when_to_use=when_to_use,
        anti_examples=anti_examples,
        colloquial_examples=colloquial_examples,
        required_slots=required_slots or [],
        optional_slots=optional_slots or [],
        slot_extraction_hints=slot_extraction_hints or {},
        risk_level=_spec_value(tool, 'risk_level', 'low'),
        side_effect=side_effect,
        allowed_roles=list(_spec_value(tool, 'allowed_roles', [])),
        executor=base_executor,
        confirmation_policy=(
            confirmation_policy
            or ('always_pending_confirmation' if side_effect else 'not_required_for_read_only')
        ),
        desensitization_policy=(
            desensitization_policy
            or ('tool_executor_and_handler_guardrails')
        ),
        verification_rules=verification_rules or [
            f'executor.tool must equal {tool}',
            'execute only through ToolExecutor',
            'respect guardrails.check_skill_permission',
        ],
        fallback_policy=fallback_policy,
        priority=priority,
        aliases=aliases or [],
    )


